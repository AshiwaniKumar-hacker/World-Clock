/**
 * Helper to find a region by country + region name
 */
export const findTimezone = (country, regionName) => {
  const countryData = timezoneData.find(c => c.country === country);
  if (!countryData) return null;
  return countryData.regions.find(r => r.name === regionName) || null;
};

/**
 * Get all available countries for dropdown
 */
